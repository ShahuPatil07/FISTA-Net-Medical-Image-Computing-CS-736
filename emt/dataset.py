"""
emt/dataset.py
==============
EMTDataset — loads pre-generated HDF5 files produced by emt/generate_data.py.
Returns (measurement_b, image_gt) pairs normalised to [0, 1].

Usage
-----
    from emt.dataset import EMTDataset, build_emt_loaders
    train_loader, val_loader, test_loader = build_emt_loaders()
"""

import sys
from pathlib import Path

import numpy as np
import h5py
import torch
from torch.utils.data import Dataset, DataLoader

sys.path.insert(0, str(Path(__file__).parent.parent))
from config import EMT, EMT_DATA_DIR


class EMTDataset(Dataset):
    """
    Loads a single HDF5 split (train / test) generated by emt/generate_data.py.

    Parameters
    ----------
    split    : "train" | "test"
    data_dir : directory containing emt_{split}.h5
    max_size : truncate dataset to this many samples (None = use all)
    """

    def __init__(
        self,
        split:    str  = "train",
        data_dir: Path = EMT_DATA_DIR,
        max_size: int  = None,
    ):
        h5_path = Path(data_dir) / f"emt_{split}.h5"
        assert h5_path.exists(), (
            f"HDF5 file not found: {h5_path}\n"
            f"Run  python emt/generate_data.py  first."
        )

        with h5py.File(h5_path, "r") as f:
            images = f["images"][:]        # (N, H, W)  conductivity contrast
            meas   = f["measurements"][:]  # (N, M)     differential voltages

        if max_size is not None:
            images = images[:max_size]
            meas   = meas[:max_size]

        # Normalise images to [0, 1]
        img_max = images.max()
        if img_max > 0:
            images = images / img_max

        # Normalise measurements to zero-mean, unit-std
        meas_mean = meas.mean(axis=0, keepdims=True)
        meas_std  = meas.std(axis=0,  keepdims=True) + 1e-8
        meas      = (meas - meas_mean) / meas_std

        self.images = torch.tensor(images, dtype=torch.float32).unsqueeze(1)  # N×1×H×W
        self.meas   = torch.tensor(meas,   dtype=torch.float32)               # N×M

        print(f"EMTDataset [{split}]: {len(self.images)} samples | "
              f"image {images.shape[1]}x{images.shape[2]} | meas_dim {meas.shape[1]}")

    def __len__(self):
        return len(self.images)

    def __getitem__(self, idx):
        return self.meas[idx], self.images[idx]   # (M,) , (1, H, W)


def build_emt_loaders(
    data_dir:   Path = EMT_DATA_DIR,
    batch_size: int  = EMT["batch_size"],
    num_workers: int = EMT["num_workers"],
    val_fraction: float = 0.1,
):
    """
    Returns (train_loader, val_loader, test_loader).
    Splits the train HDF5 into train/val by val_fraction.
    """
    from torch.utils.data import random_split

    full_train = EMTDataset("train", data_dir)
    n_val      = max(1, int(len(full_train) * val_fraction))
    n_train    = len(full_train) - n_val
    train_ds, val_ds = random_split(
        full_train, [n_train, n_val],
        generator=torch.Generator().manual_seed(42),
    )
    test_ds = EMTDataset("test", data_dir)

    train_loader = DataLoader(train_ds, batch_size=batch_size, shuffle=True,
                              num_workers=num_workers)
    val_loader   = DataLoader(val_ds,   batch_size=batch_size, shuffle=False,
                              num_workers=num_workers)
    test_loader  = DataLoader(test_ds,  batch_size=batch_size, shuffle=False,
                              num_workers=num_workers)

    return train_loader, val_loader, test_loader


def load_sensitivity_matrix(data_dir: Path = EMT_DATA_DIR) -> np.ndarray:
    """Load the pre-computed sensitivity matrix A (N_MEAS x n_elements)."""
    path = Path(data_dir) / "sensitivity_matrix_A.npy"
    assert path.exists(), f"sensitivity_matrix_A.npy not found in {data_dir}"
    return np.load(path)
